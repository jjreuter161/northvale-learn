// THE COURSE INDEX — what the app needs before any unit's cards and
// questions load: units and lessons (titles, the "In real life" line,
// minutes, the concepts each lesson tests, its tool, its card titles for
// the tutor's search) and each concept's name. Written to
// src/modules/lessons/units/index.gen.js; `npm run build` runs this, and
// the content test checks the file is up to date.
//   node scripts/lesson-index.mjs          (write)
//   node scripts/lesson-index.mjs --check  (exit 1 if it's out of date)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { UNITS } from "../src/modules/lessons/units/all.js";
import { minutesOf, isQuestion } from "../src/modules/lessons/units/time.js";

const FILE = join(import.meta.dirname, "../src/modules/lessons/units/index.gen.js");
const index = UNITS.map((u) => ({
  id: u.id,
  icon: u.icon,
  title: u.title,
  concepts: u.concepts.map((c) => ({ id: c.id, name: c.name })),
  lessons: u.lessons.map((l) => ({
    id: l.id,
    title: l.title,
    life: l.life,
    minutes: Math.round(minutesOf(l) * 100) / 100,
    concepts: [...new Set(l.steps.filter(isQuestion).map((s) => s.c))],
    action: (l.steps.find((s) => s.type === "action") || {}).kind || null,
    cards: l.steps.filter((s) => s.type === "card").map((s) => s.title),
  })),
}));
const out = `// Generated by scripts/lesson-index.mjs from the unit files. Don't edit.\nexport const INDEX = ${JSON.stringify(index)};\n`;
if (process.argv.includes("--check")) {
  if (!existsSync(FILE) || readFileSync(FILE, "utf8") !== out) (console.error("The course index is out of date: run node scripts/lesson-index.mjs"), process.exit(1));
} else writeFileSync(FILE, out);
