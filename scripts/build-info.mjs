// Writes src/core/build.gen.js: which commit and day this build is, shown in Settings > About
// so anyone can tell which version they are looking at. `npm run build` runs this first.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const git = (...a) => { try { return execFileSync("git", a, { cwd: join(import.meta.dirname, ".."), stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { return ""; } };
const commit = git("rev-parse", "--short", "HEAD") || "unknown";
const dirty = git("status", "--porcelain", "--", "src", "web/index.html") ? "+" : "";
const day = new Date().toLocaleDateString("en-CA");
writeFileSync(join(import.meta.dirname, "../src/core/build.gen.js"), `// Generated by scripts/build-info.mjs. Don't edit or commit.\nexport const BUILD = ${JSON.stringify({ commit: commit + dirty, day })};\n`);
