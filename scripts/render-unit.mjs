// Renders one unit to a Markdown page a human reviewer can read, in English
// (US numbers) and Spanish (Mexico numbers), with the right answers marked.
//   node scripts/render-unit.mjs sending     -> docs/reviews/draft/sending.md
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { UNITS as ALL_UNITS, ADDITIONS } from "../src/modules/lessons/units/all.js";
import { FACTS } from "../src/core/facts.js";
import { pick, fill } from "../src/core/i18n.js";
import { minutesOf } from "../src/modules/lessons/units/time.js";

// A unit, or "<unit>-additions" for the draft lessons added to a live unit (units/additions.js).
const UNITS = [
  ...ALL_UNITS,
  ...ADDITIONS.map((a) => {
    const base = ALL_UNITS.find((u) => u.id === a.unit);
    return { id: `${a.unit}-additions`, draft: true, title: { en: `${base.title.en} (added lessons)`, es: `${base.title.es} (lecciones nuevas)` }, sources: a.sources, concepts: a.concepts, lessons: a.lessons };
  }),
];
const unit = UNITS.find((u) => u.id === process.argv[2]);
if (!unit) (console.error(`usage: node scripts/render-unit.mjs <unit id>  (one of: ${UNITS.map((u) => u.id).join(", ")})`), process.exit(1));

const L = {
  en: { card: "Card", q: "Question", act: "Action", right: "Right", why: "Why", miss: "If picked", ans: "Answer", steps: "Steps", fit: { good: "Good", ok: "OK", poor: "Poor" } },
  es: { card: "Tarjeta", q: "Pregunta", act: "Acción", right: "Correcta", why: "Por qué", miss: "Si la eliges", ans: "Respuesta", steps: "Pasos", fit: { good: "Buena", ok: "Regular", poor: "Floja" } },
};
const render = (lang, reg) => {
  const t = (x) => (x ? fill(pick(x, lang, reg), { lang, region: reg }) : "");
  const n = (a) => (Array.isArray(a) ? a[reg === "MX" ? 1 : 0] : a);
  const w = L[lang];
  const step = (s) => {
    if (s.type === "card") return `**${w.card}: ${t(s.title)}**\n\n> ${t(s.body)}`;
    if (s.type === "action") return `**${w.act}** (\`${s.kind}\`): ${t(s.prompt)}`;
    const head = `**${w.q} (${s.type}, \`${s.c}\`):** ${t(s.q)}`;
    const why = [].concat(s.why || []).map(t).join(" → ");
    if (s.type === "choice") return `${head}\n\n${s.options.map((o, i) => `- ${i === s.answer ? "✅" : "◻️"} ${t(o)}${s.miss[i] ? `\n  - *${w.miss}:* ${t(s.miss[i])}` : ""}`).join("\n")}\n\n*${w.why}:* ${why}`;
    if (s.type === "tf") return `${head} → **${s.answer}**\n\n*${w.why}:* ${why}`;
    if (s.type === "number" || s.type === "estimate") return `${head}\n\n- ${w.ans}: **${n(s.spec.answer)}**\n- ${w.steps}: ${why}`;
    if (s.type === "match") return `${head}\n\n${s.pairs.map((p) => `- ${t(p[0])} = ${t(p[1])}`).join("\n")}\n\n*${w.why}:* ${why}`;
    if (s.type === "order") return `${head}\n\n${s.items.map((x, i) => `${i + 1}. ${t(x)}`).join("\n")}\n\n*${w.why}:* ${why}`;
    if (s.type === "scenario") return `${head}\n\n${s.options.map((o) => `- **${w.fit[o.fit]}:** ${t(o.text)} (${t(o.why)})`).join("\n")}\n\n*${w.why}:* ${why}`;
    return `${head}\n\n(${s.type}: see the unit file)`;
  };
  const concepts = unit.concepts.map((c) => `### Idea: ${t(c.name)}\n\n${step(c.explain)}\n\n${step(c.easy)}\n\n${step(c.challenge)}`).join("\n\n");
  const lessons = unit.lessons.map((l) => `### ${t(l.title)}\n\n*${lang === "en" ? "In real life" : "En la vida real"}:* ${t(l.life)}  \n*${minutesOf(l, lang).toFixed(1)} min*\n\n${l.steps.map(step).join("\n\n")}`).join("\n\n---\n\n");
  return `## ${t(unit.title)}\n\n## ${lang === "en" ? "Lessons" : "Lecciones"}\n\n${lessons}\n\n## ${lang === "en" ? "Ideas (each has an explainer, an easy and a harder question)" : "Ideas (cada una con explicación, pregunta fácil y pregunta difícil)"}\n\n${concepts}`;
};

// Border units write both countries at once; "Both" units have Mexico text that differs, so show every language and country that exists.
const hasMX = /"MX":\{/.test(JSON.stringify(unit));
const sections = [["English (US numbers)", "en", "US"], ["Español (números de México)", "es", "MX"], ...(hasMX ? [["English (Mexico version)", "en", "MX"], ["Español (versión de EE. UU.)", "es", "US"]] : [])];
const facts = [...new Set(JSON.stringify(unit).match(/\{@(\w+)\}/g) || [])].map((f) => f.slice(2, -1));
const md = `# Review copy: ${unit.title.en}${unit.draft ? " (DRAFT, not in the app)" : ""}

Generated by \`node scripts/render-unit.mjs ${unit.id}\` from \`src/modules/lessons/units/${unit.id}.js\`. Fix the unit file, not this page. ✅ marks the right answer. English shows US numbers and Spanish shows Mexico numbers (border units write both countries' amounts as dollars and pesos).

## Sources (checked on the date shown)

${(unit.sources || []).map((s) => `- ${s.name}: ${s.url} (checked ${s.checked})`).join("\n")}

## Facts this unit uses

${facts.length ? facts.map((f) => `- \`${f}\` = ${JSON.stringify(FACTS[f].value)}: ${FACTS[f].check}`).join("\n") : "- none"}

## What the reviewer checks (docs/CONTENT-ROADMAP.md, "What a human reviewer … checks")

1. Rules, limits and dates are current. 2. Nothing reads as personal advice. 3. Risk is described honestly. 4. Both countries are right, including the border cases. 5. Legal and tax content is read by a licensed professional. 6. Nothing asks a teen to open an account, apply, buy or share numbers. 7. Sign-off goes in \`docs/reviews/wave-1.md\`.

---

${sections.map(([title, lang, reg]) => `# ${title}\n\n${render(lang, reg)}`).join("\n\n---\n\n")}
`;
const dir = join(import.meta.dirname, "../docs/reviews/draft");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, `${unit.id}.md`), md);
console.log(`docs/reviews/draft/${unit.id}.md (${md.split("\n").length} lines)`);
